use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn collect_rs_files(dir: &Path, out: &mut Vec<PathBuf>) {
    println!("cargo:rerun-if-changed={}", dir.display());
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    let mut paths: Vec<PathBuf> = entries.filter_map(|e| e.ok().map(|e| e.path())).collect();
    paths.sort();

    for path in paths {
        if path.is_dir() {
            collect_rs_files(&path, out);
        } else if path.extension().and_then(|e| e.to_str()) == Some("rs") {
            println!("cargo:rerun-if-changed={}", path.display());
            out.push(path);
        }
    }
}

/// Extracts component struct names from `#[component] impl <StructName>` blocks in a Rust source file.
/// Falls back to the file stem if no explicit `#[component]` impl block is found.
fn extract_component_structs(source: &str, fallback_stem: &str) -> Vec<String> {
    let mut names = Vec::new();
    let mut saw_component_attr = false;

    for line in source.lines() {
        let trimmed = line.trim();
        if trimmed == "#[component]" || trimmed == "#[directedtype_macros::component]" {
            saw_component_attr = true;
            continue;
        }
        if saw_component_attr {
            if trimmed.starts_with('#') || trimmed.starts_with("//") || trimmed.is_empty() {
                continue;
            }
            if let Some(rest) = trimmed.strip_prefix("impl ") {
                let ident: String = rest
                    .chars()
                    .take_while(|c| c.is_alphanumeric() || *c == '_')
                    .collect();
                if !ident.is_empty() && !names.contains(&ident) {
                    names.push(ident);
                }
            }
            saw_component_attr = false;
        }
    }

    if names.is_empty() {
        names.push(fallback_stem.to_string());
    }
    names
}

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let components_dir = manifest_dir.join("components");

    let mut rs_files = Vec::new();
    if components_dir.exists() {
        collect_rs_files(&components_dir, &mut rs_files);
    }

    // Sort shallower paths first (e.g. `components/Button.rs` before `components/material/Button.rs`)
    // so top-level components take default unqualified precedence in ComponentRegistry.
    rs_files.sort_by(|a, b| {
        let rel_a = a.strip_prefix(&manifest_dir).unwrap_or(a);
        let rel_b = b.strip_prefix(&manifest_dir).unwrap_or(b);
        let depth_a = rel_a.components().count();
        let depth_b = rel_b.components().count();
        depth_a.cmp(&depth_b).then_with(|| rel_a.cmp(rel_b))
    });

    let mut generated = String::new();
    generated.push_str("// Auto-generated by build.rs — do not edit manually.\n");
    generated.push_str("#[allow(non_snake_case, dead_code, unused_imports)]\n");
    generated.push_str("mod builtin_components {\n");

    let mut registrations = Vec::new();

    for abs_path in &rs_files {
        let rel_path = abs_path
            .strip_prefix(&manifest_dir)
            .unwrap_or(abs_path)
            .to_string_lossy()
            .replace('\\', "/");

        let stem = abs_path
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or("Component");

        let mod_ident: String = format!(
            "comp_{}",
            rel_path
                .trim_end_matches(".rs")
                .chars()
                .map(|c| if c.is_alphanumeric() { c } else { '_' })
                .collect::<String>()
        );

        let abs_str = abs_path.to_string_lossy().replace('\\', "/");
        generated.push_str(&format!("    #[path = {:?}]\n", abs_str));
        generated.push_str(&format!("    pub mod {};\n", mod_ident));

        let src = fs::read_to_string(abs_path).unwrap_or_default();
        let struct_names = extract_component_structs(&src, stem);
        for struct_name in struct_names {
            registrations.push((struct_name, rel_path.clone(), mod_ident.clone()));
        }
    }

    generated.push_str("\n    pub fn register_all(registry: &mut crate::component::ComponentRegistry) {\n");
    for (struct_name, rel_path, mod_ident) in registrations {
        generated.push_str(&format!(
            "        registry.register_companion({:?}, {:?}, || Box::new({}::{}::default()));\n",
            struct_name, rel_path, mod_ident, struct_name
        ));
    }
    generated.push_str("    }\n");
    generated.push_str("}\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("builtin_components.rs"), generated)
        .expect("Failed to write builtin_components.rs");
}

